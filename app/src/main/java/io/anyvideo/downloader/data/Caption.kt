package io.anyvideo.downloader.data

import android.content.Context
import io.anyvideo.downloader.net.Http
import java.io.File
import java.util.Locale

/** One caption track offered by a YouTube player reply. */
data class CaptionTrack(
    val language: String,
    val label: String,
    val url: String,
    val autoGenerated: Boolean = false,
)

/** One sidecar subtitle file found for a saved video. */
data class CaptionFile(
    val label: String,
    val file: File,
)

/** One timed line in a subtitle file. */
data class CaptionCue(
    val startMs: Long,
    val endMs: Long,
    val text: String,
)

/**
 * Subtitles are kept next to the app, not inside the video. The display name of the saved media
 * is the key, so a downloaded file and its sidecar travel together even when MediaStore had to
 * add a numeric suffix to avoid a name collision.
 */
object CaptionStore {
    private const val FOLDER = "subtitles"
    private val unsafeName = Regex("[^A-Za-z0-9._-]")
    private val textTag = Regex(
        """<text\b([^>]*)>(.*?)</text>""",
        setOf(RegexOption.DOT_MATCHES_ALL, RegexOption.IGNORE_CASE),
    )
    private val startAttribute = Regex("""\bstart\s*=\s*"([^"]*)"""")
    private val durationAttribute = Regex("""\bdur\s*=\s*"([^"]*)"""")

    private fun directory(context: Context): File =
        File(context.filesDir, FOLDER).apply { mkdirs() }

    private fun safe(value: String): String =
        value.replace(unsafeName, "_").ifBlank { "captions" }.take(160)

    private fun filesFor(context: Context, mediaName: String): List<File> {
        val prefix = "${safe(mediaName)}."
        return directory(context).listFiles()
            .orEmpty()
            .filter { it.isFile && it.name.startsWith(prefix) }
    }

    private fun fileFor(context: Context, mediaName: String, label: String): File =
        File(directory(context), "${safe(mediaName)}.${safe(label)}.vtt")

    /** Downloads [track] and stores it as a WebVTT sidecar for [mediaName]. Never throws. */
    fun save(context: Context, mediaName: String, track: CaptionTrack?) {
        if (track == null || mediaName.isBlank() || track.url.isBlank()) return
        runCatching {
            val body = Http.get(
                captionUrl(track.url),
                headers = mapOf(
                    "User-Agent" to Http.DESKTOP_UA,
                    "Accept-Language" to "en,en-US;q=0.9",
                ),
            ) ?: return
            val vtt = toVtt(body) ?: return
            fileFor(context, mediaName, track.label).apply {
                parentFile?.mkdirs()
                writeText(vtt)
            }
        }
    }

    /** Every sidecar saved for this display name. */
    fun available(context: Context, mediaName: String): List<CaptionFile> {
        val prefix = "${safe(mediaName)}."
        return filesFor(context, mediaName)
            .asSequence()
            .filter { it.extension.equals("vtt", true) }
            .map { file ->
                val label = file.name
                    .removePrefix(prefix)
                    .removeSuffix(".vtt")
                    .replace('_', ' ')
                    .replace(Regex("\\s+"), " ")
                    .trim()
                    .ifBlank { "Captions" }
                CaptionFile(label = label, file = file)
            }
            .sortedBy { it.label.lowercase(Locale.ROOT) }
            .toList()
    }

    fun read(file: CaptionFile): List<CaptionCue> =
        runCatching { CaptionParser.parse(file.file.readText()) }.getOrDefault(emptyList())

    /** Removes every sidecar belonging to a deleted or replaced media item. */
    fun delete(context: Context, mediaName: String) {
        filesFor(context, mediaName).forEach { runCatching { it.delete() } }
    }

    private fun captionUrl(url: String): String {
        val withVtt = url.replace(Regex("([?&])fmt=[^&]*"), "$1fmt=vtt")
        if (Regex("[?&]fmt=").containsMatchIn(withVtt)) return withVtt
        return withVtt + if (withVtt.contains('?')) "&fmt=vtt" else "?fmt=vtt"
    }

    /**
     * The timedtext endpoint normally answers XML; asking for VTT is preferred, but old or
     * special tracks can ignore the format parameter. Both shapes are accepted.
     */
    private fun toVtt(body: String): String? {
        val text = body.trim().removePrefix("\uFEFF")
        if (text.isEmpty()) return null
        if (text.startsWith("WEBVTT", true) || text.contains("-->")) return text
        if (!text.contains("<text", true)) return null
        return xmlToVtt(text)
    }

    private fun xmlToVtt(xml: String): String? {
        val cues = textTag.findAll(xml).mapNotNull { match ->
            val attributes = match.groupValues[1]
            val start = startAttribute.find(attributes)?.groupValues?.get(1)
                ?.toDoubleOrNull() ?: return@mapNotNull null
            val duration = durationAttribute.find(attributes)?.groupValues?.get(1)
                ?.toDoubleOrNull() ?: 1.0
            val text = cleanCaptionText(match.groupValues[2])
            if (text.isBlank()) return@mapNotNull null
            val startMs = (start * 1000.0).toLong().coerceAtLeast(0L)
            CaptionCue(
                startMs = startMs,
                endMs = (startMs + (duration * 1000.0).toLong()).coerceAtLeast(startMs + 1L),
                text = text,
            )
        }.toList()
        if (cues.isEmpty()) return null
        return buildString {
            append("WEBVTT\n\n")
            cues.forEach { cue ->
                append(timestamp(cue.startMs))
                append(" --> ")
                append(timestamp(cue.endMs))
                append('\n')
                append(cue.text)
                append("\n\n")
            }
        }.trimEnd() + "\n"
    }

    private fun timestamp(ms: Long): String {
        val safe = ms.coerceAtLeast(0L)
        val hours = safe / 3_600_000
        val minutes = (safe % 3_600_000) / 60_000
        val seconds = (safe % 60_000) / 1_000
        val millis = safe % 1_000
        return String.format(Locale.US, "%02d:%02d:%02d.%03d", hours, minutes, seconds, millis)
    }
}

/** Parses the small WebVTT/SRT subset the sidecars use and finds the active cue. */
object CaptionParser {
    fun parse(text: String): List<CaptionCue> {
        val blocks = text
            .replace("\r\n", "\n")
            .replace('\r', '\n')
            .removePrefix("\uFEFF")
            .split(Regex("\\n\\s*\\n"))
        return blocks.mapNotNull { block ->
            val lines = block.lines()
            val timingIndex = lines.indexOfFirst { it.contains("-->") }
            if (timingIndex < 0) return@mapNotNull null
            val timing = lines[timingIndex]
            val start = parseTime(timing.substringBefore("-->")) ?: return@mapNotNull null
            val end = parseTime(
                timing.substringAfter("-->").trim().substringBefore(' '),
            ) ?: return@mapNotNull null
            val content = cleanCaptionText(lines.drop(timingIndex + 1).joinToString("\n"))
            if (content.isBlank() || end <= start) null
            else CaptionCue(startMs = start, endMs = end, text = content)
        }.sortedBy { it.startMs }
    }

    fun currentCue(cues: List<CaptionCue>, positionMs: Long): CaptionCue? =
        cues.lastOrNull { positionMs >= it.startMs && positionMs < it.endMs }

    fun current(cues: List<CaptionCue>, positionMs: Long): String? =
        currentCue(cues, positionMs)?.text

    private fun parseTime(value: String): Long? {
        val parts = value.trim().replace(',', '.').split(':')
        if (parts.size !in 2..3) return null
        val seconds = parts.last().toDoubleOrNull() ?: return null
        val minutes = parts[parts.size - 2].toDoubleOrNull() ?: return null
        val hours = if (parts.size == 3) parts[0].toDoubleOrNull() ?: return null else 0.0
        return ((hours * 3600.0 + minutes * 60.0 + seconds) * 1000.0).toLong().coerceAtLeast(0L)
    }
}

/** Removes the tiny amount of markup YouTube puts inside a cue and decodes its entities. */
private fun cleanCaptionText(value: String): String {
    val plain = value
        .replace(Regex("<br\\s*/?>", RegexOption.IGNORE_CASE), "\n")
        .replace(Regex("<[^>]+>"), "")
        .replace('\u00A0', ' ')
    return decodeEntities(plain).trim()
}

private fun decodeEntities(value: String): String {
    var text = value
        .replace("&amp;", "&")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&nbsp;", " ")
    text = Regex("&#x([0-9a-fA-F]+);").replace(text) { match ->
        match.groupValues[1].toIntOrNull(16)?.let { String(Character.toChars(it)) } ?: match.value
    }
    text = Regex("&#([0-9]+);").replace(text) { match ->
        match.groupValues[1].toIntOrNull()?.let { String(Character.toChars(it)) } ?: match.value
    }
    return text
}
